package com.foldpapper.report;

/** Причина жалобы на пин или профиль — фиксированный список, чтобы модераторам было проще разбирать очередь. */
public enum ReportReason {
    /** Спам или реклама. */
    SPAM,
    /** Контент 18+. */
    NSFW,
    /** Оскорбления, травля, язык вражды. */
    OFFENSIVE,
    /** Нарушение авторских прав. */
    COPYRIGHT,
    /** Выдаёт себя за другого человека — только для жалоб на профиль. */
    IMPERSONATION,
    OTHER
}
